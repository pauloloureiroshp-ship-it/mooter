const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

// SHA-256 cache — skip regex for identical prompts within 30min
const classifyCache = new Map();
const CACHE_TTL_MS = 30 * 60 * 1000;

function getCached(prompt) {
  const hash = crypto.createHash('sha256').update(prompt).digest('hex');
  const entry = classifyCache.get(hash);
  if (entry && Date.now() - entry.ts < CACHE_TTL_MS) {
    return { ...entry.result, cached: true };
  }
  return null;
}

function setCache(prompt, result) {
  const hash = crypto.createHash('sha256').update(prompt).digest('hex');
  classifyCache.set(hash, { result, ts: Date.now() });
}

// MD Enrichment — read ## Router Context block from project CLAUDE.md
function readRouterContext() {
  const claudeMdPath = path.join(process.cwd(), 'CLAUDE.md');
  try {
    const content = fs.readFileSync(claudeMdPath, 'utf8');
    const match = content.match(/## Router Context\n([\s\S]*?)(?=\n## |\n# |$)/);
    if (!match) return {};

    const ctx = {};
    const lines = match[1].split('\n');
    for (const line of lines) {
      const [key, ...rest] = line.split(':');
      if (key && rest.length) {
        const val = rest.join(':').trim().replace(/#.*$/, '').trim();
        ctx[key.trim()] = val;
      }
    }
    return ctx;
  } catch {
    return {};
  }
}

