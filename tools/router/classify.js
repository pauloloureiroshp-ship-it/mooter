const TUNED_COMPLEXITY_THRESHOLD = 0.25;
const TUNED_PROMOTE_T0 = [];
const TUNED_DEMOTE_T3 = [/\bporque\s+é\s+que\b/i, /\bdecompõe\s+o\s+sprint\b/i];
