'use strict';

/**
 * generate-mooter-skills.js — idempotent writer for the dynamic
 * `/mooter-<slug>` pin slash commands.
 *
 * For every *available* model in the catalog it writes
 * `<skillsDir>/mooter-<slug>/SKILL.md`. The skill body is instruction-driven:
 * when Claude Code loads the skill (because the user typed `/mooter-<slug>`),
 * the body tells the agent to honor a single-message pin of that model. This
 * mechanism — rather than a per-turn env var — is what gives the "this message
 * only" semantics: the skill is only loaded for the message that invoked it,
 * so nothing leaks into later turns.
 *
 * SAFETY — marker-scoped cleanup:
 *   The skills directory already contains many hand-written `mooter-*` skills
 *   (mooter-auto, mooter-review, mooter-status, …). A naive "remove every
 *   mooter-* dir not in the catalog" cleanup would delete all of them. Instead,
 *   every generated SKILL.md carries PIN_MARKER and cleanup ONLY removes dirs
 *   whose SKILL.md contains that marker. Hand-written skills are never touched.
 */

const fs = require('fs');
const path = require('path');
const { paths } = require('./paths');
const { discoverAllModels, flattenModels } = require('./discover-models');

/** Embedded in every generated SKILL.md; gates marker-scoped cleanup. */
const PIN_MARKER = '<!-- mooter:generated-pin-skill v1 -->';

function defaultSkillsDir() {
  return path.join(paths.claude, 'skills');
}

/** Per-tier dispatch instruction for Anthropic pins. */
function anthropicDispatchLine(m) {
  switch (m.tier) {
    case 'T3':
      return 'Handle this message at full Opus depth directly (the session is already Opus). '
        + 'Spawn `model-architect` only if genuine isolation or parallelization is needed.';
    case 'T2':
      return 'Spawn the `model-reasoner` subagent (Sonnet) to handle this message.';
    case 'T1':
      return 'Spawn the `cheap-triage` subagent (Haiku) to handle this message.';
    default:
      return `Dispatch via the \`${m.subagent}\` subagent.`;
  }
}

/** Build the SKILL.md body for an Anthropic model entry. */
function buildAnthropicSkillBody(m) {
  return `---
name: mooter-${m.slug}
description: Pin Anthropic ${m.displayName} for this message only. Forces tier ${m.tier} and dispatches to the ${m.subagent} subagent. Use when you explicitly want ${m.displayName} regardless of automatic routing.
---
${PIN_MARKER}
<!-- AUTO-GENERATED by tools/cli/lib/generate-mooter-skills.js — do not edit by hand; \`mooter doctor\` overwrites it. -->

# \`/mooter-${m.slug}\` — Pin ${m.displayName}

Pin **${m.displayName}** (\`${m.model}\`) for the **current message only**. The next message returns to mooter's automatic routing.

## What this does

- Treats this message as a \`user_override\` pinning ${m.displayName}.
- Target tier **${m.tier}** → subagent **${m.subagent}**.
- Pin scope: **single message** — it does NOT persist to later turns (this skill is only loaded for the message that invoked it).

## Instructions for the agent

For THIS message only, honor a user override pinning ${m.displayName}:

- Tier **${m.tier}**, subagent **${m.subagent}**.
- ${anthropicDispatchLine(m)}
- Do NOT downgrade to a cheaper tier for cost reasons — the user explicitly asked for ${m.displayName}.
- Keep it transparent: do not add a note reminding the user that a pin was active.

If the shell that launched Claude Code exported \`MOOTER_PIN_MODEL=${m.model}\`, the router hook additionally emits \`USER_OVERRIDE: honored — pinned to ${m.model}\` in the \`<router-hint>\`. That env var is optional; the pin above applies regardless.
`;
}

/**
 * Build the SKILL.md body for a non-Anthropic model (Codex CLI, OpenAI direct,
 * Ollama). These are dispatched via router-execute.js, so the reply surfaces as
 * a tool result — the body documents that leaky UX honestly.
 */
function buildNonAnthropicSkillBody(m) {
  const modelLabel = m.model || 'CLI default model';
  const pinModelLine = m.model ? `  --pin-model=${m.model} \\\n` : '';
  return `---
name: mooter-${m.slug}
description: Run this message via ${m.displayName} (${m.provider}). Invokes router-execute directly; the reply appears as a tool result the agent relays. Pin scope: single message only.
---
${PIN_MARKER}
<!-- AUTO-GENERATED by tools/cli/lib/generate-mooter-skills.js — do not edit by hand; \`mooter doctor\` overwrites it. -->

# \`/mooter-${m.slug}\` — Run via ${m.displayName}

Dispatches the current prompt to **${m.displayName}** (${modelLabel}, provider \`${m.provider}\`) through \`router-execute.js\`. The response returns as a tool result; the agent relays it.

## UX caveat (read this)

Claude Code's session model is Claude, not ${m.displayName}. The reply from ${m.displayName} appears as **tool output**, not as a native answer from the agent — the agent quotes/relays it. This is expected and unavoidable while the session host is Claude.

## Behavior

- Single-message dispatch — no session-level pin.
- Cost is recorded in \`~/.claude/tools/router/quota-state.json\`.
- Provider call timeout: 30s default (override with \`MOOTER_PER_ATTEMPT_TIMEOUT_MS\`).
- On provider failure the error is surfaced — there is NO silent fallback to Anthropic.

## Instructions for the agent

Run this Bash command, replacing \`<USER PROMPT>\` with the user's prompt verbatim. Then present the \`text\` field of the JSON result as the response (do not summarize unless asked). If \`outcome !== 'ok'\`, present the error and stop.

\`\`\`bash
node ~/.claude/tools/router/router-execute.js \\
  --pin-provider=${m.provider} \\
${pinModelLine}  --prompt-stdin <<'PROMPT_EOF'
<USER PROMPT>
PROMPT_EOF
\`\`\`
`;
}

/** Dispatch to the right template by provider. */
function buildSkillBody(m) {
  if (!m.provider || m.provider === 'anthropic') return buildAnthropicSkillBody(m);
  return buildNonAnthropicSkillBody(m);
}

/**
 * Generate (or verify) the mooter pin skills.
 *
 * @param {object} [opts]
 * @param {boolean} [opts.dryRun]   plan only, never touch the filesystem
 * @param {string}  [opts.skillsDir] override target dir (tests)
 * @param {Array}   [opts.models]    override catalog (tests / Sessão B)
 * @returns {{written:string[], removed:string[], skipped:string[]}}
 */
function generateMooterSkills(opts = {}) {
  const dryRun = !!opts.dryRun;
  const skillsDir = opts.skillsDir || defaultSkillsDir();
  const models = opts.models || flattenModels(discoverAllModels());
  const available = models.filter((m) => m && m.available);
  const keepSlugs = new Set(available.map((m) => m.slug));

  const written = [];
  const skipped = [];
  const removed = [];

  // 1. Write / refresh available models (idempotent: skip when unchanged).
  for (const m of available) {
    const name = `mooter-${m.slug}`;
    const dir = path.join(skillsDir, name);
    const file = path.join(dir, 'SKILL.md');
    const desired = buildSkillBody(m);
    let current = null;
    try { current = fs.readFileSync(file, 'utf8'); } catch { /* absent */ }
    if (current === desired) {
      skipped.push(name);
      continue;
    }
    if (!dryRun) {
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(file, desired);
    }
    written.push(name);
  }

  // 2. Marker-scoped cleanup: remove ONLY generated pin skills whose model is
  //    no longer available. Hand-written mooter-* skills (no marker) are safe.
  let entries = [];
  try { entries = fs.readdirSync(skillsDir, { withFileTypes: true }); } catch { /* dir absent */ }
  for (const e of entries) {
    if (!e.isDirectory() || !e.name.startsWith('mooter-')) continue;
    const slug = e.name.slice('mooter-'.length);
    if (keepSlugs.has(slug)) continue; // still current → leave it
    const file = path.join(skillsDir, e.name, 'SKILL.md');
    let content = null;
    try { content = fs.readFileSync(file, 'utf8'); } catch { continue; }
    if (!content.includes(PIN_MARKER)) continue; // hand-written → NEVER remove
    if (!dryRun) {
      fs.rmSync(path.join(skillsDir, e.name), { recursive: true, force: true });
    }
    removed.push(e.name);
  }

  return { written, removed, skipped };
}

module.exports = {
  generateMooterSkills,
  buildSkillBody,
  buildAnthropicSkillBody,
  buildNonAnthropicSkillBody,
  PIN_MARKER,
};
